#!/usr/bin/env python3
from dataclasses import dataclass
from pathlib import Path

@dataclass
class OpField:
    name: str
    type: str
    nary: bool = False

@dataclass
class Op:
    name: str
    fields: [OpField]
    returns: bool = True

def binop(name):
    return Op(name, [
        OpField("lhs", "Value"),
        OpField("rhs", "Value"),
    ])

OPS = [
    Op("If", [
        OpField("cond", "Value"),
        OpField("ifBranch", "Block"),
        OpField("elseBranch", "Block"),
    ], returns=False),
    Op("Loop", [
        OpField("body", "Block"),
    ], returns=False),
    Op("Return", [
        OpField("val", "Value"),
    ], returns=False),
    Op("Continue", [], returns=False),
    Op("Break", [], returns=False),
    Op("Const", [
        OpField("data", "std::byte", nary=True),
    ]),
    Op("Call", [
        OpField("target", "DefFunction*"),
        OpField("args", "Value", nary=True),
    ]),
    Op("CallIndirect", [
        OpField("targetAddr", "Value"),
        OpField("args", "Value", nary=True),
    ]),
    Op("FieldPtr", [
        OpField("base", "Value"),
        OpField("fieldIdx", "unsigned"),
    ]),
    Op("Alloca", [
        OpField("size", "Value"),
    ]),
    Op("Cast", [
        OpField("input", "Value"),
    ]),
    Op("Load", [
        OpField("base", "Value"),
    ]),
    Op("Store", [
        OpField("target", "Value"),
        OpField("value", "Value"),
    ], returns=False),
    Op("DefAddr", [
        OpField("def", "Def*"),
    ]),
    Op("Cmp", [
        OpField("lhs", "Value"),
        OpField("cmp", "Comparator"),
        OpField("rhs", "Value"),
    ]),
    Op("BitNot", [
        OpField("input", "Value"),
    ]),
    binop("Add"),
    binop("Sub"),
    binop("Mul"),
    binop("Div"),
    binop("BitAnd"),
    binop("BitOr"),
    binop("BitXor"),
    binop("ShiftLeft"),
    binop("ShiftRight"),
]

def field_decl(field):
    if field.nary:
        return f"{field.type} {field.name}[];"
    return f"{field.type} {field.name};"

def write_kind_enum(f):
    print("enum class OpKind {", file=f)
    for op in OPS:
        print(f"  {op.name},", file=f)
    print("};", file=f)

def write_op_classes(f):
    for op in OPS:
        print(f"struct {op.name}Op : public Operation {{", file=f)
        for field in op.fields:
            print(f"  {field_decl(field)}", file=f)
        print("};", file=f)

def build_param(field):
    if field.nary:
        return f"std::span<const {field.type}> {field.name}"
    return f"{field.type} {field.name}"

def write_build_decl(f):
    for op in OPS:
        params = [f"std::vector<std::byte> &", "Loc loc"]
        if op.returns:
            params.append("Type returnType")
        params += [build_param(field) for field in op.fields]

        print(f"Value build{op.name}({', '.join(params)});", file=f)

def write_build_impl(f):
    for op in OPS:
        struct = f"{op.name}Op"
        fixed = [field for field in op.fields if not field.nary]
        nary = [field for field in op.fields if field.nary]
        assert len(nary) <= 1 and (not nary or op.fields[-1].nary), \
            f"{op.name}: n-ary field must be last"
        buf = "opStorageBuffer"
        params = [f"std::vector<std::byte> &{buf}", "Loc loc"]
        if op.returns:
            params.append("Type returnType")
        params += [build_param(field) for field in op.fields]
        size = f"sizeof({struct})"
        if nary:
            size += f" + {nary[0].name}.size() * sizeof({nary[0].type})"
        inits = [f"OpKind::{op.name}", "loc"]
        if op.returns:
            inits.append("returnType")
        else:
            inits.append("Type()")
        inits += [field.name for field in fixed]

        print(f"Value build{op.name}({', '.join(params)}) {{", file=f)
        print(f"  auto off = {buf}.size();", file=f)
        print(f"  {buf}.resize(off + {size});", file=f)
        print(f"  auto *op = reinterpret_cast<{struct} *>(&{buf}[off]);", file=f)
        print(f"  *op = {struct}{{{', '.join(inits)}}};", file=f)
        if nary:
            name = nary[0].name
            print(f"  std::copy({name}.begin(), {name}.end(), op->{name});", file=f)
        print("  return Value{unsigned(off)};", file=f)
        print("}", file=f)

def write_inc(f):
    print("// Generated by ops.py. Do not edit.", file=f)

    # Kind enum
    print("#ifdef GEN_OP_KIND", file=f)
    write_kind_enum(f)
    print("#undef GEN_OP_KIND", file=f)
    print("#endif // GEN_OP_KIND", file=f)
    print("", file=f)

    # Op classes
    print("#ifdef GEN_OP_CLASSES", file=f)
    write_op_classes(f)
    print("#undef GEN_OP_CLASSES", file=f)
    print("#endif // GEN_OP_CLASSES", file=f)
    print("", file=f)

    # builder declarations
    print("#ifdef GEN_OP_BUILD_DECL", file=f)
    write_build_decl(f)
    print("#undef GEN_OP_BUILD_DECL", file=f)
    print("#endif // GEN_OP_BUILD_DECL", file=f)
    print("", file=f)

    # builder implementations
    print("#ifdef GEN_OP_BUILD_IMPL", file=f)
    write_build_impl(f)
    print("#undef GEN_OP_BUILD_IMPL", file=f)
    print("#endif // GEN_OP_BUILD_IMPL", file=f)

if __name__ == "__main__":
    out_path = Path(__file__).resolve().parent / "Operation.inc.h"
    with open(out_path, "w") as f:
        write_inc(f)
