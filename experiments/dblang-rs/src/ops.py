#!/usr/bin/env python3
"""Generates src/ir/generated.rs: the OpKind enum and the <Name>Op structs."""
import subprocess
from dataclasses import dataclass, field
from pathlib import Path


@dataclass
class OpField:
    name: str
    type: str
    nary: bool = False


@dataclass
class Op:
    name: str
    fields: list[OpField] = field(default_factory=list)
    returns: bool = True


def binop(name):
    return Op(name, [
        OpField("lhs", "Value"),
        OpField("rhs", "Value"),
    ])


OPS = [
    Op("If", [
        OpField("cond", "Value"),
        OpField("if_branch", "BlockRef"),
        OpField("else_branch", "BlockRef"),
    ], returns=False),
    Op("Loop", [
        OpField("body", "BlockRef"),
    ], returns=False),
    Op("Return", [
        OpField("val", "Value"),
    ], returns=False),
    Op("Continue", [], returns=False),
    Op("Break", [], returns=False),
    Op("Const", [
        OpField("value", "Const"),
    ]),
    Op("Call", [
        OpField("func", "DefRef"),
        OpField("args", "Value", nary=True),
    ]),
    Op("CallIndirect", [
        OpField("target_addr", "Value"),
        OpField("args", "Value", nary=True),
    ]),
    Op("FieldPtr", [
        OpField("base", "Value"),
        OpField("field_idx", "u32"),
    ]),
    Op("Alloca", [
        OpField("size", "Value"),
    ]),
    Op("Cast", [
        OpField("input", "Value"),
    ]),
    Op("Load", [
        OpField("base", "Value"),
    ]),
    Op("Store", [
        OpField("target", "Value"),
        OpField("value", "Value"),
    ], returns=False),
    Op("DefAddr", [
        OpField("def", "DefRef"),
    ]),
    Op("Cmp", [
        OpField("lhs", "Value"),
        OpField("cmp", "Comparator"),
        OpField("rhs", "Value"),
    ]),
    Op("BitNot", [
        OpField("input", "Value"),
    ]),
    binop("Add"),
    binop("Sub"),
    binop("Mul"),
    binop("Div"),
    binop("BitAnd"),
    binop("BitOr"),
    binop("BitXor"),
    binop("ShiftLeft"),
    binop("ShiftRight"),
]


def field_type(f):
    return f"Vec<{f.type}>" if f.nary else f.type


def write_kind_enum(out):
    print("pub enum OpKind {", file=out)
    for op in OPS:
        print(f"    {op.name}({op.name}Op),", file=out)
    print("}", file=out)


def write_op_structs(out):
    for op in OPS:
        if not op.fields:
            print(f"\npub struct {op.name}Op;", file=out)
            continue
        print(f"\npub struct {op.name}Op {{", file=out)
        for f in op.fields:
            print(f"    pub {f.name}: {field_type(f)},", file=out)
        print("}", file=out)


def snake_case(name):
    return "".join(
        f"_{c.lower()}" if c.isupper() and i > 0 else c.lower()
        for i, c in enumerate(name)
    )


def write_builder_impl(out):
    print("\nimpl<'a> OpBuilder<'a> {", file=out)
    for i, op in enumerate(OPS):
        if i > 0:
            print("", file=out)
        params = ["&mut self"]
        if op.returns:
            params.append("result_type: Type")
        params += [f"{f.name}: {field_type(f)}" for f in op.fields]
        ret = " -> Value" if op.returns else ""
        print(f"    pub fn build_{snake_case(op.name)}({', '.join(params)}){ret} {{",
              file=out)

        if op.fields:
            field_names = ", ".join(f.name for f in op.fields)
            kind = f"OpKind::{op.name}({op.name}Op {{ {field_names} }})"
        else:
            kind = f"OpKind::{op.name}({op.name}Op)"

        if op.returns:
            print(f"        self.insert_op(result_type, {kind})", file=out)
        else:
            print(f"        self.insert_op(Type::void(), {kind});", file=out)
        print("    }", file=out)
    print("}", file=out)


def write_gen(out):
    print("// Generated by ops.py. Do not edit.", file=out)
    print("use super::*;", file=out)
    print("", file=out)
    write_kind_enum(out)
    write_op_structs(out)
    write_builder_impl(out)


if __name__ == "__main__":
    out_path = Path(__file__).resolve().parent / "ir" / "generated.rs"
    out_path.parent.mkdir(exist_ok=True)
    with open(out_path, "w") as out:
        write_gen(out)
    subprocess.run(["rustfmt", "--edition", "2024", str(out_path)], check=True)
