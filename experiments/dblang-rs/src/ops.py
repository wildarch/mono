#!/usr/bin/env python3
"""Generates src/ir/generated.rs: the OpKind enum and the <Name>Op structs."""
from dataclasses import dataclass, field
from pathlib import Path


@dataclass
class OpField:
    name: str
    type: str
    nary: bool = False


@dataclass
class Op:
    name: str
    fields: list[OpField] = field(default_factory=list)
    returns: bool = True


def binop(name):
    return Op(name, [
        OpField("lhs", "Value"),
        OpField("rhs", "Value"),
    ])


OPS = [
    Op("If", [
        OpField("cond", "Value"),
        OpField("if_branch", "Block"),
        OpField("else_branch", "Block"),
    ], returns=False),
    Op("Loop", [
        OpField("body", "Block"),
    ], returns=False),
    Op("Return", [
        OpField("val", "Value"),
    ], returns=False),
    Op("Continue", [], returns=False),
    Op("Break", [], returns=False),
    Op("Const", [
        OpField("value", "Const"),
    ]),
    Op("Call", [
        OpField("func", "Function"),
        OpField("args", "Value", nary=True),
    ]),
    Op("CallIndirect", [
        OpField("target_addr", "Value"),
        OpField("args", "Value", nary=True),
    ]),
    Op("FieldPtr", [
        OpField("base", "Value"),
        OpField("field_idx", "u32"),
    ]),
    Op("Alloca", [
        OpField("size", "Value"),
    ]),
    Op("Cast", [
        OpField("input", "Value"),
    ]),
    Op("Load", [
        OpField("base", "Value"),
    ]),
    Op("Store", [
        OpField("target", "Value"),
        OpField("value", "Value"),
    ], returns=False),
    Op("DefAddr", [
        OpField("def", "Def"),
    ]),
    Op("Cmp", [
        OpField("lhs", "Value"),
        OpField("cmp", "Comparator"),
        OpField("rhs", "Value"),
    ]),
    Op("BitNot", [
        OpField("input", "Value"),
    ]),
    binop("Add"),
    binop("Sub"),
    binop("Mul"),
    binop("Div"),
    binop("BitAnd"),
    binop("BitOr"),
    binop("BitXor"),
    binop("ShiftLeft"),
    binop("ShiftRight"),
]


def field_type(f):
    return f"Vec<{f.type}>" if f.nary else f.type


def write_kind_enum(out):
    print("pub enum OpKind {", file=out)
    for op in OPS:
        print(f"    {op.name}({op.name}Op),", file=out)
    print("}", file=out)


def write_op_structs(out):
    for op in OPS:
        if not op.fields:
            print(f"\npub struct {op.name}Op;", file=out)
            continue
        print(f"\npub struct {op.name}Op {{", file=out)
        for f in op.fields:
            print(f"    pub {f.name}: {field_type(f)},", file=out)
        print("}", file=out)


def write_gen(out):
    print("// Generated by ops.py. Do not edit.", file=out)
    print("use super::*;", file=out)
    print("", file=out)
    write_kind_enum(out)
    write_op_structs(out)


if __name__ == "__main__":
    out_path = Path(__file__).resolve().parent / "ir" / "generated.rs"
    out_path.parent.mkdir(exist_ok=True)
    with open(out_path, "w") as out:
        write_gen(out)
